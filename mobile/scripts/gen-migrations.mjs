// Copies the backend's Flyway migrations into the app, so the phone's schema is byte-for-byte the
// desktop's (docs/SYNC_PROTOCOL.md §1). Run after adding a backend migration: npm run migrations
import { readdirSync, readFileSync, writeFileSync } from 'node:fs'
import { dirname, join } from 'node:path'
import { fileURLToPath } from 'node:url'

const here = dirname(fileURLToPath(import.meta.url))
const source = join(here, '..', '..', 'backend', 'src', 'main', 'resources', 'db', 'migration')
const target = join(here, '..', 'src', 'db', 'migrations.generated.ts')

const files = readdirSync(source)
  .map((name) => ({ name, m: /^V(\d+)__(.+)\.sql$/.exec(name) }))
  .filter((f) => f.m)
  .map((f) => ({ version: Number(f.m[1]), name: f.name, sql: readFileSync(join(source, f.name), 'utf8').replace(/\r\n/g, '\n') }))
  .sort((a, b) => a.version - b.version)

files.forEach((f, i) => {
  if (f.version !== i + 1) throw new Error(`Migrations must be numbered 1..n without gaps; found ${f.name}`)
})

const body = files
  .map((f) => `  { version: ${f.version}, name: ${JSON.stringify(f.name)}, sql: ${JSON.stringify(f.sql)} },`)
  .join('\n')

writeFileSync(
  target,
  `// GENERATED by scripts/gen-migrations.mjs from backend/src/main/resources/db/migration. Do not edit.\n` +
    `export interface Migration {\n  version: number\n  name: string\n  sql: string\n}\n\n` +
    `export const MIGRATIONS: Migration[] = [\n${body}\n]\n`,
)
console.log(`Wrote ${files.length} migrations to ${target}`)
